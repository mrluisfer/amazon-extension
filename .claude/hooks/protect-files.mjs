#!/usr/bin/env node
// PreToolUse hook: blocks edits to secrets, the lockfile and applied migrations.
// Exit code 2 blocks the tool call and feeds stderr back to Claude.
import { basename, relative } from 'node:path';

let input = '';
process.stdin.on('data', (chunk) => {
  input += chunk;
});
process.stdin.on('end', () => {
  let filePath = '';
  try {
    filePath = JSON.parse(input)?.tool_input?.file_path ?? '';
  } catch {
    process.exit(0);
  }
  if (!filePath) process.exit(0);

  const root = process.env.CLAUDE_PROJECT_DIR ?? process.cwd();
  const rel = relative(root, filePath).replaceAll('\\', '/');
  const name = basename(filePath);

  const rules = [
    [
      /^\.env(\..+)?$/.test(name) && name !== '.env.example',
      'Secrets files (.env*) are off-limits. Edit the matching .env.example instead.',
    ],
    [name.endsWith('.pem'), 'Signing keys must never be touched by tooling.'],
    [name === 'pnpm-lock.yaml', 'Do not hand-edit the lockfile; use pnpm add/remove.'],
    [
      /^packages\/db\/migrations\/.+/.test(rel),
      'Migrations are generated by `pnpm db:generate` and immutable once committed. Change packages/db/src/schema.ts instead.',
    ],
  ];

  for (const [blocked, reason] of rules) {
    if (blocked) {
      process.stderr.write(`Blocked edit to ${rel}: ${reason}\n`);
      process.exit(2);
    }
  }
  process.exit(0);
});
